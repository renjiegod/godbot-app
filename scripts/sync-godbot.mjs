// Copies the code the app shares with Godbot into godbot/, from a dsh-godbot checkout.
//
//   node scripts/sync-godbot.mjs           copy and write godbot/SOURCE.json
//   node scripts/sync-godbot.mjs --check   exit 1 when godbot/ differs from its source
//
// GODBOT_SRC   the dsh-godbot checkout (default ../dsh-godbot-wt/phone-link-push, then ../dsh-godbot)
//
// The copies are never edited by hand: a change goes into dsh-godbot first, then here.
// Without a source checkout, --check verifies the copies against the hashes in SOURCE.json.
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

export const APP = dirname(dirname(fileURLToPath(import.meta.url)))
const TARGET = 'godbot'

// [source path relative to the checkout, target path relative to godbot/]
export const CLIENT_FILES = [
  ['src/client/theme.js', 'client/theme.js'],
  ['src/client/team-ui/themes.js', 'client/team-ui/themes.js'],
  ['src/client/team-ui/inks.js', 'client/team-ui/inks.js'],
  ['src/client/team-ui/characters.js', 'client/team-ui/characters.js'],
  ['src/client/team-ui/sources.js', 'client/team-ui/sources.js'],
  ['src/client/team-ui/i18n.js', 'client/team-ui/i18n.js'],
]
export const SHARED_FILES = [
  ['src/host/team-runtime/shared/work-board.js', 'shared/work-board.js'],
  ['src/host/team-runtime/shared/im-platforms.js', 'shared/im-platforms.js'],
  ['src/host/team-runtime/shared/file-chunks.js', 'shared/file-chunks.js'],
]

const sha256 = data => createHash('sha256').update(data).digest('hex')

function firstExisting(paths) {
  return paths.find(path => path !== undefined && existsSync(path))
}

function gitCommit(dir) {
  try {
    const commit = execFileSync('git', ['-C', dir, 'rev-parse', 'HEAD'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim()
    const dirty = execFileSync('git', ['-C', dir, 'status', '--porcelain'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim() !== ''
    return { commit, dirty }
  } catch {
    return { commit: null, dirty: null }
  }
}

/** Every [absolute source, target] pair, or a reason why the sources are not there. */
export function plan(env = process.env, app = APP) {
  const godbot = firstExisting([env.GODBOT_SRC && resolve(env.GODBOT_SRC), resolve(app, '../dsh-godbot-wt/phone-link-push'), resolve(app, '../dsh-godbot')])
  if (godbot === undefined) return { error: 'No dsh-godbot checkout: set GODBOT_SRC' }
  const linkDir = join(godbot, 'src/link')
  if (!existsSync(join(linkDir, 'index.ts'))) return { error: `${godbot} has no src/link/index.ts: use a dsh-godbot checkout with the link sources` }
  const pairs = []
  for (const name of readdirSync(linkDir).sort()) {
    if (name.endsWith('.ts') && !name.endsWith('.test.ts') && !name.endsWith('.d.ts')) pairs.push([join(linkDir, name), `link/${name}`])
  }
  for (const [from, to] of [...CLIENT_FILES, ...SHARED_FILES]) pairs.push([join(godbot, from), to])
  const locales = join(godbot, 'src/client/team-ui/locales')
  for (const name of readdirSync(locales).sort()) {
    if (name.endsWith('.js')) pairs.push([join(locales, name), `client/team-ui/locales/${name}`])
  }
  const missing = pairs.filter(([from]) => !existsSync(from)).map(([from]) => from)
  if (missing.length > 0) return { error: `Missing source files:\n${missing.join('\n')}` }
  return { godbot, pairs }
}

export function sourceRecord(planned) {
  const files = {}
  for (const [from, to] of planned.pairs) files[to] = sha256(readFileSync(from))
  return {
    note: 'Generated by scripts/sync-godbot.mjs. Do not edit the files under godbot/ by hand.',
    godbot: gitCommit(planned.godbot),
    files,
  }
}

function listTarget(root) {
  const out = []
  if (!existsSync(root)) return out
  const walk = dir => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name)
      if (entry.isDirectory()) walk(path)
      else if (entry.name !== 'SOURCE.json') out.push(relative(root, path))
    }
  }
  walk(root)
  return out.sort()
}

/** Differences between godbot/ and either the sources or the recorded hashes. */
export function check(app = APP, env = process.env) {
  const root = join(app, TARGET)
  const planned = plan(env, app)
  const problems = []
  if (planned.error === undefined) {
    const expected = new Map(planned.pairs.map(([from, to]) => [to, sha256(readFileSync(from))]))
    for (const [to, hash] of expected) {
      const path = join(root, to)
      if (!existsSync(path)) problems.push(`missing ${to}`)
      else if (sha256(readFileSync(path)) !== hash) problems.push(`differs ${to}`)
    }
    for (const extra of listTarget(root)) if (!expected.has(extra)) problems.push(`extra ${extra}`)
    return { problems, against: 'source' }
  }
  let record
  try { record = JSON.parse(readFileSync(join(root, 'SOURCE.json'), 'utf8')) } catch { return { problems: ['no SOURCE.json and no source checkout'], against: 'record' } }
  for (const [to, hash] of Object.entries(record.files ?? {})) {
    const path = join(root, to)
    if (!existsSync(path)) problems.push(`missing ${to}`)
    else if (sha256(readFileSync(path)) !== hash) problems.push(`differs ${to}`)
  }
  for (const extra of listTarget(root)) if (!Object.hasOwn(record.files ?? {}, extra)) problems.push(`extra ${extra}`)
  return { problems, against: 'record' }
}

export function sync(app = APP, env = process.env) {
  const planned = plan(env, app)
  if (planned.error !== undefined) throw new Error(planned.error)
  const root = join(app, TARGET)
  rmSync(root, { recursive: true, force: true })
  for (const [from, to] of planned.pairs) {
    const path = join(root, to)
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, readFileSync(from))
  }
  const record = sourceRecord(planned)
  writeFileSync(join(root, 'SOURCE.json'), `${JSON.stringify(record, null, 2)}\n`)
  return { record, count: planned.pairs.length }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const { problems, against } = check()
    if (problems.length > 0) {
      console.error(`godbot/ is out of date (checked against the ${against}):\n${problems.join('\n')}\nRun: node scripts/sync-godbot.mjs`)
      process.exit(1)
    }
    console.log(`godbot/ matches its ${against}`)
  } else {
    const { count, record } = sync()
    console.log(`Copied ${count} files into godbot/ from dsh-godbot ${record.godbot.commit ?? '(unknown commit)'}${record.godbot.dirty ? ' with uncommitted changes' : ''}`)
  }
}
