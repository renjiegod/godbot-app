// Release builds refuse plain HTTP and ws://, except to this phone itself and to the
// computer that runs the Android emulator (10.0.2.2). A relay elsewhere must use wss://.
// The debug build's Metro connection goes over adb reverse to localhost, which stays allowed.
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins')
const { mkdirSync, writeFileSync } = require('node:fs')
const { join } = require('node:path')

const CLEARTEXT_HOSTS = ['localhost', '127.0.0.1', '10.0.2.2']

function networkSecurityXml(hosts = CLEARTEXT_HOSTS) {
  const domains = hosts.map(host => `        <domain includeSubdomains="false">${host}</domain>`).join('\n')
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/network-security.js -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
    <domain-config cleartextTrafficPermitted="true">
${domains}
    </domain-config>
</network-security-config>
`
}

function withNetworkSecurity(config) {
  config = withDangerousMod(config, ['android', async (next) => {
    const dir = join(next.modRequest.platformProjectRoot, 'app/src/main/res/xml')
    mkdirSync(dir, { recursive: true })
    writeFileSync(join(dir, 'network_security_config.xml'), networkSecurityXml())
    return next
  }])
  return withAndroidManifest(config, (next) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(next.modResults)
    app.$['android:networkSecurityConfig'] = '@xml/network_security_config'
    delete app.$['android:usesCleartextTraffic']
    return next
  })
}

module.exports = withNetworkSecurity
module.exports.networkSecurityXml = networkSecurityXml
module.exports.CLEARTEXT_HOSTS = CLEARTEXT_HOSTS
